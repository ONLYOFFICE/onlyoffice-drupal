#!/usr/bin/env bash
#
# Local development stand: Drupal + ONLYOFFICE Docs with this module mounted into Drupal.
# Usage: dev/stand.sh [up|down|destroy|drush <args>|composer <args>|shell|logs [service]]

set -euo pipefail
# Git Bash would otherwise rewrite container paths such as /opt/drupal into Windows paths.
export MSYS_NO_PATHCONV=1

DEV_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$DEV_DIR"

if [ -f .env ]; then
    set -a
    . ./.env
    set +a
fi

export DRUPAL_VERSION="${DRUPAL_VERSION:-10.3}"
export PHP_VERSION="${PHP_VERSION:-8.3}"
export DRUPAL_PORT="${DRUPAL_PORT:-8000}"
export DS_PORT="${DS_PORT:-8080}"
export DS_JWT_SECRET="${DS_JWT_SECRET:-onlyoffice-drupal-dev-stand-secret}"
ADMIN_USER="${ADMIN_USER:-admin}"
ADMIN_PASS="${ADMIN_PASS:-admin}"

MODULE_DIR=/opt/drupal/web/modules/contrib/onlyoffice
SITE_DIR=/opt/drupal/web/sites/default

log() {
    printf '\033[1;34m==>\033[0m %s\n' "$*"
}

compose() {
    docker compose "$@"
}

as_root() {
    compose exec -T -w /opt/drupal drupal "$@"
}

drush() {
    compose exec -T --user www-data -e HOME=/tmp -w /opt/drupal drupal \
        vendor/bin/drush --uri="http://localhost:$DRUPAL_PORT" "$@"
}

# The module's own composer requirements, plus drush for the stand itself.
install_packages() {
    local missing=()
    local package
    while IFS= read -r package; do
        [ -n "$package" ] || continue
        if ! as_root composer show --locked --no-interaction "${package%%:*}" </dev/null >/dev/null 2>&1; then
            missing+=("$package")
        fi
    done < <(as_root php -r '
        $json = json_decode(file_get_contents($argv[1] . "/composer.json"), TRUE);
        foreach ($json["require"] as $name => $version) {
            if ($name !== "drupal/core") echo "$name:$version\n";
        }
        echo "drush/drush\n";
    ' "$MODULE_DIR")

    if [ ${#missing[@]} -gt 0 ]; then
        log "Installing ${missing[*]}"
        as_root composer require --no-interaction "${missing[@]}"
    fi
}

write_settings() {
    as_root sh -c "cat > $SITE_DIR/settings.stand.php" <<'PHP'
<?php

// Generated by dev/stand.sh on every start; edits are overwritten.

// Browsers use localhost, ONLYOFFICE Docs uses the docker service name.
$settings['trusted_host_patterns'] = ['^localhost$', '^drupal$'];
$settings['skip_permissions_hardening'] = TRUE;

// There is no mail server in the stand; sent mail is kept in the state instead.
$config['system.mail']['interface']['default'] = 'test_mail_collector';

$config['system.logging']['error_level'] = 'verbose';
$config['system.performance']['css']['preprocess'] = FALSE;
$config['system.performance']['js']['preprocess'] = FALSE;
PHP
}

# Before the install, so that the installer already runs with the stand settings.
include_settings() {
    as_root sh -c "
        cd $SITE_DIR
        [ -f settings.php ] || cp default.settings.php settings.php
        chown www-data:www-data settings.php
        grep -q settings.stand.php settings.php || cat >> settings.php
    " <<'PHP'

if (file_exists($app_root . '/' . $site_path . '/settings.stand.php')) {
  include $app_root . '/' . $site_path . '/settings.stand.php';
}
PHP
}

is_installed() {
    [ "$(drush status --field=bootstrap 2>/dev/null)" = "Successful" ]
}

cmd_up() {
    if [ -z "$(ls -A ../assets/document-templates 2>/dev/null)" ]; then
        log "Initialising the document-templates submodule"
        git -C .. submodule update --init --recursive
    fi

    log "Starting containers (Document Server takes a minute or two on first start)"
    compose up -d --wait db drupal documentserver

    install_packages
    as_root chown -R www-data:www-data "$SITE_DIR"
    write_settings
    include_settings

    if is_installed; then
        log "Updating the database"
        drush updatedb -y
    else
        log "Installing Drupal"
        drush site:install standard -y \
            --db-url=mysql://drupal:drupal@db:3306/drupal \
            --site-name="ONLYOFFICE dev" --site-mail=admin@example.com \
            --account-name="$ADMIN_USER" --account-pass="$ADMIN_PASS" --account-mail=admin@example.com
    fi

    log "Enabling and configuring the ONLYOFFICE modules"
    drush pm:install -y media onlyoffice onlyoffice_form
    drush config:set -y onlyoffice.settings doc_server_url "http://localhost:$DS_PORT"
    drush config:set -y onlyoffice.settings doc_server_internal_url "http://documentserver"
    drush config:set -y onlyoffice.settings storage_url "http://drupal"
    drush config:set -y onlyoffice.settings doc_server_jwt "$DS_JWT_SECRET"
    drush cache:rebuild

    log "Checking the connection to ONLYOFFICE Docs"
    drush php:eval '
        try {
            echo "Connected, ONLYOFFICE Docs " . \Drupal::service("onlyoffice.document_service")->checkConnection() . "\n";
        }
        catch (\RuntimeException $e) {
            echo "Connection check failed: " . $e->getMessage() . "\n";
        }
    '

    cat <<EOF

Drupal:          http://localhost:$DRUPAL_PORT  ($ADMIN_USER / $ADMIN_PASS)
ONLYOFFICE Docs: http://localhost:$DS_PORT
Module mounted:  $MODULE_DIR
EOF
}

command="${1:-up}"
[ $# -gt 0 ] && shift

case "$command" in
    up)       cmd_up ;;
    down)     compose down ;;
    destroy)  compose down --volumes ;;
    drush)    drush "$@" ;;
    composer) as_root composer "$@" ;;
    shell)    compose exec drupal bash ;;
    logs)     compose logs -f "$@" ;;
    *)
        echo "Usage: $0 [up|down|destroy|drush <args>|composer <args>|shell|logs [service]]" >&2
        exit 1
        ;;
esac
